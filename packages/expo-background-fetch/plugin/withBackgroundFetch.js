'use strict';

const fs = require('node:fs/promises');
const path = require('node:path');

const { createRunOncePlugin } = require('@expo/config-plugins');
const {
  HarmonyManifest,
  HarmonyPaths,
  withHarmonyDangerousMod,
  withHarmonyGeneratedFiles,
  withModuleJson,
} = require('@expo-harmony/config-plugins');

const pkg = require('../package.json');

const EXTENSION_NAME = 'ExpoBackgroundFetchWorkSchedulerExtension';
const EXTENSION_SOURCE = `./ets/expo-background-fetch/${EXTENSION_NAME}.ets`;
const EXTENSION_PATH = path.posix.join(path.posix.dirname(HarmonyPaths.HARMONY_PATHS.moduleJson), EXTENSION_SOURCE);
const GENERATED_MARKER = 'Automatically generated by @expo-harmony/expo-background-fetch.';
const GENERATED_SOURCE = `/**
 * ${GENERATED_MARKER}
 */

import {
  ${EXTENSION_NAME} as ${EXTENSION_NAME}Base,
} from '@expo-harmony/expo-background-fetch';

export default class ${EXTENSION_NAME}
  extends ${EXTENSION_NAME}Base {}
`;

const withBackgroundFetch = (config) => {
  const enabled = config.harmony?.bundleName || config.platforms?.includes('harmony');
  if (!enabled) return config;

  config = withModuleJson(config, (mod) => {
    if (mod.modResults.module === undefined) mod.modResults.module = {};
    HarmonyManifest.ensureExtensionAbility(mod.modResults, {
      name: EXTENSION_NAME,
      srcEntry: EXTENSION_SOURCE,
      type: 'workScheduler',
      exported: false,
    });
    return mod;
  });

  config = withHarmonyGeneratedFiles(config, {
    owner: pkg.name,
    files: { [EXTENSION_PATH]: { content: GENERATED_SOURCE } },
  });

  // Dangerous mods run in reverse order, so the guard runs before the writers.
  return withHarmonyDangerousMod(config, async (mod) => {
    if (mod.modRequest.introspect) return mod;

    const file = await HarmonyPaths.resolveHarmonyPath(mod.modRequest.platformProjectRoot, EXTENSION_PATH);
    const current = await fs.readFile(file, 'utf8').catch((error) => {
      if (error.code !== 'ENOENT') throw error;
    });

    if (current !== undefined && !current.includes(GENERATED_MARKER)) {
      throw new TypeError(`Harmony source '${file}' already exists and is not managed by ${pkg.name}.`);
    }

    return mod;
  });
};

module.exports = createRunOncePlugin(withBackgroundFetch, pkg.name, pkg.version);
