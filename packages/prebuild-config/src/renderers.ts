import type { HarmonyBuildDescriptor } from './buildDescriptor';
import { MODULE_NAME_PLACEHOLDER, TEMPLATE_PLACEHOLDERS } from './template';

const ReactNativeConfigHeader = '// Generated by @expo-harmony/prebuild-config. Customize through withReactNativeConfig.';
const LoadRnohConfig = `require(path.join(path.dirname(resolveRnohCliPackageJsonPath()), 'react-native.config.js'))`;

function isGeneratedReactNativeConfig(source: string): boolean {
  const normalized = source.replace(/\r\n?/gu, '\n');
  const direct = `${ReactNativeConfigHeader}
module.exports = require('@react-native-oh/react-native-harmony-cli/react-native.config.js');
`;
  const hoisted = `${ReactNativeConfigHeader}
const path = require('node:path');
const { resolveRnohCliPackageJsonPath } = require('@expo-harmony/expo-modules-autolinking');
module.exports = ${LoadRnohConfig};
`;
  return normalized === direct
    || normalized === hoisted
    || normalized === renderReactNativeConfig()
    || normalized === renderReactNativeConfig(true);
}

function renderCanonical(source, label) {
  if (typeof source !== 'string' || !source.trim()) {
    throw new TypeError(`${label} must start from the canonical Harmony template source.`);
  }

  return source.replace(/\r\n?/gu, '\n');
}

function replacePlaceholder(source, placeholder, value, label) {
  const count = source.split(placeholder).length - 1;

  if (count !== 1) {
    throw new TypeError(
      `Canonical Harmony template has ${count} ${label} placeholders; expected exactly one.`
    );
  }

  return source.replace(placeholder, () => value);
}

function quoteSingle(value) {
  return `'${String(value)
    .replace(/\\/gu, '\\\\')
    .replace(/'/gu, `\\'`)
    .replace(/\r/gu, '\\r')
    .replace(/\n/gu, '\\n')}'`;
}

function renderReactNativeConfig(esm = false) {
  const imports = esm
    ? `import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);`
    : `const path = require('node:path');
const { createRequire } = require('node:module');`;

  return `${ReactNativeConfigHeader}
${imports}
const requirePrebuild = createRequire(require.resolve('@expo-harmony/prebuild-config/package.json'));
const { resolveRnohCliPackageJsonPath } = requirePrebuild('@expo-harmony/expo-modules-autolinking');
${esm ? 'export default' : 'module.exports ='} ${LoadRnohConfig};
`;
}

function renderRootHvigor(source, build: HarmonyBuildDescriptor) {
  source = renderCanonical(source, build.projectFiles.rootHvigor);

  return replacePlaceholder(
    source,
    quoteSingle(TEMPLATE_PLACEHOLDERS.bundlePath),
    quoteSingle(build.export.bundle),
    'embedded bundle path'
  );
}

function renderEntryAbility(source, harmony) {
  source = renderCanonical(source, 'EntryAbility.ets');

  return replacePlaceholder(
    source,
    TEMPLATE_PLACEHOLDERS.abilityName,
    harmony.abilityName,
    'ability class'
  );
}

function renderPackageProvider(source, harmony) {
  source = renderCanonical(source, 'PackageProvider.ets');
  const moduleName = JSON.stringify(MODULE_NAME_PLACEHOLDER);
  if (source.includes(moduleName)) {
    source = replacePlaceholder(source, moduleName, JSON.stringify(harmony.moduleName), 'worker module name');
  }

  return replacePlaceholder(
    source,
    JSON.stringify(TEMPLATE_PLACEHOLDERS.appLabel),
    JSON.stringify(harmony.label),
    'RN instance name'
  );
}

export {
  isGeneratedReactNativeConfig,
  renderCanonical,
  renderEntryAbility,
  renderPackageProvider,
  renderReactNativeConfig,
  renderRootHvigor,
};
