import type { ModuleDescriptor } from '../../types';
import { resolveRnohMetadata } from './packageMetadata';

export function renderRnohEtsFactories(modules: readonly ModuleDescriptor[]) {
  const packages = modules
    .filter(module => module.rnoh.harPaths.length > 0)
    .map(resolveRnohMetadata);

  function render(worker: boolean) {
    const imports = [];
    const registrations = [];

    for (const [index, metadata] of packages.entries()) {
      if (metadata.etsPackageScope === 'host' || (worker && metadata.etsPackageScope === 'ui')) continue;
      const alias = `RNOHLinkedPackage${index}`;
      const binding = metadata.etsPackageImport === 'named'
        ? `{ ${metadata.etsPackageClassName} as ${alias} }`
        : alias;
      imports.push(`import ${binding} from ${JSON.stringify(metadata.harMappings[0].ohPackageName)};`);
      registrations.push(`    new ${alias}(ctx),`);
    }

    const factory = worker ? 'createRNOHWorkerPackages' : 'createRNOHPackages';

    return [
      '// Generated by @expo-harmony/expo-modules-autolinking.',
      '',
      'import type { RNPackage, RNPackageContext } from "@rnoh/react-native-openharmony";',
      ...imports,
      '',
      `export function ${factory}(ctx: RNPackageContext): RNPackage[] {`,
      '  return [',
      ...registrations,
      '  ];',
      '}',
      '',
    ].join('\n');
  }

  return { ui: render(false), worker: render(true) };
}
