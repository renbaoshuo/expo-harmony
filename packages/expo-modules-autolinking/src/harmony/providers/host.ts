import path from 'node:path';

import { HarmonyAutolinkingError } from '../../errors';
import { HostMetadataFields } from '../../metadata/host';
import { ExpoArtifacts, InlineModulesRoot } from '../../config/constants';

function collectHostExtensions(descriptors) {
  const collected = Object.fromEntries(HostMetadataFields.map(field => [field, []]));

  for (const descriptor of [...descriptors].sort((left, right) => (
    left.packageName.localeCompare(right.packageName, 'en')
  ))) {
    const declarations = HostMetadataFields.flatMap(field => descriptor.expo[field] || []);
    if (declarations.length === 0) continue;

    const name = descriptor.arkTs?.ohPackageName;
    if (!name) {
      throw new HarmonyAutolinkingError(
        'INVALID_METADATA',
        'Harmony host extension classes must be exported by the module primary HAR.',
        { packageName: descriptor.packageName, stage: 'generate-host-provider' }
      );
    }

    for (const field of HostMetadataFields) {
      for (const className of descriptor.expo[field] || []) {
        collected[field].push({ className, ohPackageName: name, packageName: descriptor.packageName });
      }
    }
  }

  return collected;
}

function moduleRegistrationId(ohPackageName, moduleClass) {
  return `${ohPackageName}:${moduleClass}`;
}

function collectArkTsModuleRegistrations(descriptors) {
  const registrations = [];

  for (const descriptor of [...descriptors].sort((left, right) => (
    left.packageName.localeCompare(right.packageName, 'en')
  ))) {
    if (descriptor.harmony.modules.length === 0) continue;

    if (descriptor.source === 'inlineModules') {
      for (const file of descriptor.inlineModules.files) {
        for (const module of file.modules) {
          registrations.push({
            moduleClass: module.name,
            importPath: './' + path.posix.relative(path.posix.dirname(ExpoArtifacts.hostProvider), path.posix.join(InlineModulesRoot, file.path)).replace(/\.ets$/, ''),
            defaultImport: module.default,
            packageName: descriptor.packageName,
            registrationId: `${descriptor.packageName}:${file.path}:${module.name}`,
          });
        }
      }
      continue;
    }

    const arkTs = descriptor.arkTs;
    if (!arkTs) {
      throw new HarmonyAutolinkingError(
        'INVALID_METADATA',
        'Harmony ArkTS modules require the conventional Harmony library package.',
        { packageName: descriptor.packageName, stage: 'generate-host-provider' }
      );
    }

    for (const moduleClass of descriptor.harmony.modules) {
      registrations.push({
        moduleClass,
        ohPackageName: arkTs.ohPackageName,
        importPath: arkTs.ohPackageName,
        defaultImport: false,
        packageName: descriptor.packageName,
        registrationId: moduleRegistrationId(arkTs.ohPackageName, moduleClass),
      });
    }
  }

  return registrations;
}

function renderArkTsHostProviderSource(descriptors) {
  const extensions = collectHostExtensions(descriptors);
  const registrations = collectArkTsModuleRegistrations(descriptors);
  const services = [...descriptors]
    .sort((left, right) => left.packageName.localeCompare(right.packageName, 'en'))
    .flatMap(descriptor => descriptor.harmony.services.map((name) => {
      if (!descriptor.arkTs) {
        throw new HarmonyAutolinkingError('INVALID_METADATA', 'Harmony services require the conventional Harmony library package.', {
          packageName: descriptor.packageName,
          stage: 'generate-host-provider',
        });
      }

      return { name, package: descriptor.arkTs.ohPackageName };
    }));
  const imports = new Map();

  for (const field of HostMetadataFields) {
    for (const extension of extensions[field]) {
      const key = `${extension.ohPackageName}\0${extension.className}`;
      if (!imports.has(key)) {
        imports.set(key, {
          ...extension,
          alias: `ExpoHarmonyHostExtension${imports.size}`,
        });
      }
      extension.alias = imports.get(key).alias;
    }
  }

  const lines = ['// Generated by @expo-harmony/expo-modules-autolinking.', ''];

  lines.push(
    ...(extensions.appLifecycleSubscribers.length || extensions.abilityLifecycleSubscribers.length || extensions.reactNativeHostHandlers.length || extensions.reactActivityHandlers.length || extensions.runtimeBindings.length ? [`import type { common } from '@kit.AbilityKit';`] : []),
    `import { ExpoHarmonyHostState } from '@expo-harmony/expo-modules-core';`,
    `import { ExpoHarmonyLifecycleDispatcher, ExpoHarmonyHostProvider } from '@expo-harmony/expo';`,
    'import type {',
    '  ReactNativeHostHandlerRegistration,',
    '  ReactActivityHandlerRegistration,',
    '  ReactRuntimeBindingRegistration,',
    ...(registrations.length > 0 ? ['  ExpoModuleContext,'] : []),
    '  ExpoModuleRegistration,',
    '  ExpoServiceClass,',
    ...(services.length > 0 ? ['  ExpoServiceContext,'] : []),
    `} from '@expo-harmony/expo-modules-core';`
  );

  registrations.forEach((registration, index) => {
    registration.alias = `ExpoHarmonyModule${index}`;
    lines.push(
      registration.defaultImport
        ? `import ${registration.alias} from ${JSON.stringify(registration.importPath)};`
        : `import { ${registration.moduleClass} as ${registration.alias} } from ${JSON.stringify(registration.importPath)};`
    );
  });

  services.forEach((service, index) => {
    lines.push(`import { ${service.name} as ExpoHarmonyService${index} } from '${service.package}';`);
  });

  for (const extension of imports.values()) {
    lines.push(
      `import { ${extension.className} as ${extension.alias} } from '${extension.ohPackageName}';`
    );
  }

  lines.push(
    '',
    'class GeneratedExpoHarmonyHostProvider implements ExpoHarmonyHostProvider {',
    '  readonly hostState: ExpoHarmonyHostState = new ExpoHarmonyHostState();',
    '',
    '  readonly lifecycle: ExpoHarmonyLifecycleDispatcher = new ExpoHarmonyLifecycleDispatcher(',
    '    ['
  );
  for (const extension of extensions.appLifecycleSubscribers) {
    lines.push(
      '      {',
      `        registrationId: ${JSON.stringify(moduleRegistrationId(extension.ohPackageName, extension.className))},`,
      `        create: (context: common.ApplicationContext) => new ${extension.alias}(context),`,
      '      },'
    );
  }
  lines.push('    ],', '    [');
  for (const extension of extensions.abilityLifecycleSubscribers) {
    lines.push(
      '      {',
      `        registrationId: ${JSON.stringify(moduleRegistrationId(extension.ohPackageName, extension.className))},`,
      `        create: (context: common.UIAbilityContext) => new ${extension.alias}(context),`,
      '      },'
    );
  }
  lines.push('    ],', '  );');
  for (const [field, type] of [
    ['reactNativeHostHandlers', 'ReactNativeHostHandlerRegistration'],
    ['reactActivityHandlers', 'ReactActivityHandlerRegistration'],
    ['runtimeBindings', 'ReactRuntimeBindingRegistration'],
  ]) {
    lines.push('', `  readonly ${field}: ${type}[] = [`);
    for (const extension of extensions[field]) {
      lines.push(
        '    {',
        `      packageName: ${JSON.stringify(extension.packageName)},`,
        `      registrationId: ${JSON.stringify(moduleRegistrationId(extension.ohPackageName, extension.className))},`,
        `      create: (context: common.Context) => new ${extension.alias}(context),`,
        '    },'
      );
    }
    lines.push('  ];');
  }
  lines.push('', '  readonly expoModules: ExpoModuleRegistration[] = [');
  for (const registration of registrations) {
    lines.push(
      '    {',
      `      registrationId: ${JSON.stringify(registration.registrationId)},`,
      `      moduleClassName: ${JSON.stringify(registration.moduleClass)},`,
      `      factory: (context: ExpoModuleContext) => new ${registration.alias}(context),`,
      '    },'
    );
  }
  lines.push(
    '  ];',
    '',
    '  readonly expoServices: ExpoServiceClass[] = [',
    ...services.flatMap((service, index) => [
      '    {',
      `      name: ${JSON.stringify(service.name)},`,
      `      create: (context: ExpoServiceContext) => new ExpoHarmonyService${index}(context),`,
      '    },',
    ]),
    '  ];',
    '}',
    '',
    'export const expoHarmonyHostProvider: ExpoHarmonyHostProvider =',
    '  new GeneratedExpoHarmonyHostProvider();',
    '',
    '@Builder',
    'export function ExpoHarmonyRootView(): void {'
  );

  for (const extension of extensions.rootViewComponents) {
    lines.push(`  ${extension.alias}()`);
  }

  lines.push('}', '');

  return lines.join('\n');
}

export {
  moduleRegistrationId,
  renderArkTsHostProviderSource,
};
