'use strict';

const { createRunOncePlugin } = require('@expo/config-plugins');
const {
  HarmonyManifest,
  HarmonyPermissions,
  registerHarmonyConfigPlugin,
  withHarmonyGeneratedFiles,
  withModuleJson,
} = require('@expo-harmony/config-plugins');

const pkg = require('../package.json');

const fenceName = 'ExpoLocationFenceExtension';
const fenceSource = `./ets/expo-location/${fenceName}.ets`;

const withLocation = (config, {
  isHarmonyBackgroundLocationEnabled: background = false,
  isHarmonyGeofencingEnabled: geofencing = false,
} = {}) => {
  if ((!background && !geofencing) || (!config.harmony?.bundleName && !config.platforms?.includes('harmony'))) return config;

  config = registerHarmonyConfigPlugin(config, pkg.name);
  config = withModuleJson(config, (mod) => {
    const manifest = mod.modResults;
    const ability = HarmonyManifest.getMainAbilityOrThrow(manifest);
    const permissions = [{
      name: 'ohos.permission.LOCATION_IN_BACKGROUND',
      reason: '$string:expo_location_background_permission_reason',
      usedScene: { abilities: [ability.name], when: 'always' },
    }];
    if (background) {
      permissions.push({ name: 'ohos.permission.KEEP_BACKGROUND_RUNNING' });
      ability.backgroundModes = [...new Set([...(ability.backgroundModes ?? []), 'location'])];
      HarmonyManifest.setMetadata(ability, { name: 'expo.location.background', value: 'true' });
    }
    if (geofencing) {
      HarmonyManifest.ensureExtensionAbility(manifest, {
        name: fenceName,
        srcEntry: fenceSource,
        type: 'fence',
        exported: false,
      });
    }
    HarmonyPermissions.ensurePermissions(manifest, permissions);

    return mod;
  });

  if (!geofencing) return config;

  return withHarmonyGeneratedFiles(config, {
    owner: pkg.name,
    files: {
      [`entry/src/main/${fenceSource.slice(2)}`]: {
        content: `// Generated by @expo-harmony/expo-location.
import { FenceExtensionAbility, geoLocationManager } from '@kit.LocationKit';
import { deliverExpoGeofenceEvent } from '@expo-harmony/expo-location/src/main/ets/LocationFenceIngress';

export default class ${fenceName} extends FenceExtensionAbility {
  override onFenceStatusChange(transition: geoLocationManager.GeofenceTransition, _additions: Record<string, string>): void {
    deliverExpoGeofenceEvent(this.context, transition);
  }
}
`,
      },
    },
  });
};

module.exports = createRunOncePlugin(withLocation, pkg.name, pkg.version);
